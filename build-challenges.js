if (require.main !== module) return;

// ---------------------------------------------------------------------
if (release) {
  const problems = releaseProblems(CHALLENGES);
  if (problems.length) {
    console.error('FAIL: Spot the Trap is not approved for release:\n  ' + problems.join('\n  '));
    process.exit(1);
  }
}

const outputs = [['spot-the-trap.html', indexPage]].concat(CHALLENGES.map((c, i) => [fileOf(c), (ex) => scenarioPage(c, i, ex)]));
let stale = [];
for (const [file, make] of outputs) {
  const p = path.join(__dirname, file);
  const existing = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  const html = make(existing);
  if (html !== existing) {
    stale.push(file);
    if (!check) fs.writeFileSync(p, html);
  }
}
if (check && stale.length) {
  console.error('FAIL: Spot the Trap pages are out of date: ' + stale.join(', ') + '. Run: node build-challenges.js');
  process.exit(1);
}
console.log(check ? 'Spot the Trap pages match challenges.js.' : outputs.length + ' page(s) built, ' + stale.length + ' changed.');
