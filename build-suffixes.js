#!/usr/bin/env node
/* =====================================================================
   REGENERATE THE PUBLIC-SUFFIX TABLE

   Run with: node build-suffixes.js

   promptscan.js carries a table of multi-label public suffixes. Deciding
   where a public suffix ends is what tells the brand checks who owns a
   domain, and getting it wrong means accusing real websites — which this
   project has already done once, to coinbase.co.uk.

   The table is a SUBSET, and it is hand-maintained by default. This
   script replaces it with a snapshot generated from the upstream Public
   Suffix List, stamped with the date it was taken.

   WHY A SNAPSHOT AND NOT A RUNTIME FETCH. The scanner runs entirely in
   the visitor's browser with no network calls; fetching a list at page
   load would break that and would make every scan depend on somebody
   else's uptime. A dated snapshot is honest about what it is.

   WHY ONLY MULTI-LABEL ENTRIES. Single-label suffixes (.com, .io, .xyz)
   need no table — anything that is not multi-label is handled by taking
   the last two labels. Carrying the other ~9,000 entries would add
   weight to a page that must stay small and change nothing.

   WHAT IT WILL NOT DO: it will not write a table it could not fetch, and
   it will not write one that fails its own sanity checks. A suffix table
   that is silently wrong is worse than one that is visibly old.
   ===================================================================== */

const fs = require('fs');
const path = require('path');
const https = require('https');

const SOURCE = 'https publicsuffix.org/list/public_suffix_list.dat'.replace(' ', '://');
const TARGET = path.join(__dirname, 'promptscan.js');
const START = '// >>> PUBLIC-SUFFIX-TABLE >>>';
const END = '// <<< PUBLIC-SUFFIX-TABLE <<<';

// Entries that must survive any regeneration. If the fetched list does
// not contain these, something is wrong with the fetch rather than with
// the list, and we stop rather than shipping a table missing the cases
// that caused the original bug.
const MUST_CONTAIN = ['co.uk', 'com.au', 'com.br', 'co.jp', 'com.tr', 'co.za', 'co.in'];

// Deliberately excluded: on these the label really is registered by
// whoever asked for it, so a wallet brand sitting on one is worth
// flagging rather than excusing. Kept as a list so the choice is
// visible and arguable rather than an accident of filtering.
const EXCLUDE_PREFIXES = ['github.io', 'gitlab.io', 'pages.dev', 'workers.dev', 'vercel.app', 'netlify.app', 'herokuapp.com', 'appspot.com', 'web.app', 'firebaseapp.com', 'r2.dev', 'amplifyapp.com'];

function fetchList(url) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, { timeout: 20000 }, res => {
      if (res.statusCode !== 200) {
        res.resume();
        return reject(new Error(`HTTP ${res.statusCode} from ${url}`));
      }
      let body = '';
      res.setEncoding('utf8');
      res.on('data', c => { body += c; });
      res.on('end', () => resolve(body));
    });
    req.on('timeout', () => { req.destroy(new Error('timed out after 20s')); });
    req.on('error', reject);
  });
}

function parse(dat) {
  const out = [];
  let inIcann = false;
  for (const raw of dat.split('\n')) {
    const line = raw.trim();
    if (line.startsWith('// ===BEGIN ICANN DOMAINS===')) { inIcann = true; continue; }
    if (line.startsWith('// ===END ICANN DOMAINS===')) { inIcann = false; continue; }
    if (!inIcann || !line || line.startsWith('//')) continue;

    // Wildcards (*.foo) and exceptions (!bar.foo) describe rules this
    // table's simple membership test cannot express. Skipping them is
    // why the result stays a subset, and why an unresolved boundary is
    // reported as unknown rather than assumed.
    if (line.startsWith('*') || line.startsWith('!')) continue;
    if (/[^a-z0-9.-]/.test(line)) continue;          // leave IDN forms alone
    if (!line.includes('.')) continue;               // single-label needs no table
    if (line.split('.').length !== 2) continue;      // deeper rules: same reason as wildcards
    if (EXCLUDE_PREFIXES.includes(line)) continue;
    out.push(line);
  }
  return [...new Set(out)].sort();
}

function render(entries, when) {
  const lines = [];
  let row = [];
  for (const e of entries) {
    row.push(`'${e}'`);
    if (row.join(',').length > 88) { lines.push('  ' + row.join(',') + ','); row = []; }
  }
  if (row.length) lines.push('  ' + row.join(',') + ',');

  return [
    START,
    `// GENERATED by build-suffixes.js on ${when} from ${SOURCE}`,
    `// ICANN section, two-label entries only, ${entries.length} suffixes.`,
    '// Wildcard and exception rules are not represented; a boundary this',
    '// table cannot resolve is reported as unknown, never guessed.',
    'const MULTI_LABEL_SUFFIXES = new Set([',
    ...lines,
    ']);',
    END,
  ].join('\n');
}

(async () => {
  let dat;
  try {
    dat = await fetchList(SOURCE);
  } catch (err) {
    console.error('FAIL: could not fetch the Public Suffix List.');
    console.error('      ' + err.message);
    console.error('\nThe table in promptscan.js was NOT modified. It remains the');
    console.error('hand-maintained subset, which is a documented, working state —');
    console.error('run this again from a machine that can reach publicsuffix.org.');
    process.exit(1);
  }

  const entries = parse(dat);
  const missing = MUST_CONTAIN.filter(m => !entries.includes(m));
  if (entries.length < 500 || missing.length) {
    console.error(`FAIL: the fetched list looks wrong (${entries.length} entries`
      + (missing.length ? `, missing ${missing.join(', ')}` : '') + ').');
    console.error('      Nothing was written. A silently wrong suffix table is worse');
    console.error('      than a visibly old one.');
    process.exit(1);
  }

  const src = fs.readFileSync(TARGET, 'utf8');
  const a = src.indexOf(START);
  const b = src.indexOf(END);
  if (a === -1 || b === -1 || b < a) {
    console.error('FAIL: could not find the table markers in promptscan.js. Nothing was written.');
    process.exit(1);
  }

  const when = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(TARGET, src.slice(0, a) + render(entries, when) + src.slice(b + END.length), 'utf8');

  console.log(`Wrote ${entries.length} suffixes into promptscan.js (snapshot ${when}).`);
  console.log('\nNow run, in this order:');
  console.log('  node promptscan.test.js     # the boundary cases');
  console.log('  node embed.js               # copy it into the page');
  console.log('  node verify_embedded.js     # prove the copy took');
  console.log('\nAnd update the UPDATED: line in the comment above the table.');
})();
